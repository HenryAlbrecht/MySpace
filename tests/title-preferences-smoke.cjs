const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const storage = new Map(), ctx = { window: {}, safeUrl: value => /^(https?:\/\/|data:image\/(png|jpeg|webp|gif);base64,)/.test(value || '') ? value : '' };
let failKey = '';
ctx.localStorage = { get length() { return storage.size; }, key: i => [...storage.keys()][i] ?? null, getItem: key => storage.get(key) ?? null, removeItem: key => storage.delete(key), setItem: (key, value) => { if (key === failKey) { failKey = ''; throw Error('Quota'); } storage.set(key, value); } };
vm.createContext(ctx); vm.runInContext(fs.readFileSync('dist/title-preferences.js', 'utf8'), ctx);
const preferences = ctx.window.TitlePreferences;
storage.set('myspace.titleBannerSettings:igdb:1', JSON.stringify({ image: 'data:image/jpeg;base64,abc', height: 420, zoom: 1.5, x: 20, y: 75 }));
storage.set('myspace.titleCover:igdb:1', 'https://example.com/jp.jpg');
storage.set('myspace.trackVideo:Artist:Song', 'https://www.youtube.com/watch?v=abcdefghijk');
storage.set('LASTFM_API_KEY', 'not-exportable');
const exported = JSON.parse(JSON.stringify(preferences.collect()));
assert.equal(Object.keys(exported).length, 3);
preferences.replace({}); assert.equal(preferences.collect()['myspace.titleCover:igdb:1'], undefined);
preferences.replace(exported);
assert.equal(JSON.parse(preferences.collect()['myspace.titleBannerSettings:igdb:1']).zoom, 1.5);
assert.equal(storage.get('LASTFM_API_KEY'), 'not-exportable');
assert.throws(() => preferences.validate({ 'LASTFM_API_KEY': 'forbidden' }));
assert.throws(() => preferences.validate({ 'myspace.titleCover:igdb:1': 'javascript:alert(1)' }));
assert.throws(() => preferences.validate({ 'myspace.titleBannerSettings:igdb:1': JSON.stringify({ image: '', height: 900, zoom: 1, x: 50, y: 50 }) }));
failKey = 'myspace.titleCover:igdb:2';
assert.throws(() => preferences.replace({ 'myspace.titleCover:igdb:2': 'https://example.com/new.jpg' }));
assert.deepEqual(JSON.parse(JSON.stringify(preferences.collect())), exported, 'A quota error must restore all previous preferences');
console.log('Title backup: custom images, crops, covers and videos round-trip; validation and quota rollback OK.');
